//! # 入站适配层（Presentation Layer）
//!
//! DDD 四层架构中的最外层，负责协议适配和用户交互。
//!
//! ## 职责
//!
//! - **协议转换**：把外部协议（HTTP、CLI）翻译成应用层调用
//! - **请求验证**：校验输入参数，转换为领域层能理解的数据结构
//! - **响应格式化**：把应用层返回值转换为外部协议格式（JSON、CLI 输出等）
//! - **用户接口**：直接与用户/客户端交互
//!
//! ## 与应用层的关系
//!
//! 入站适配层不包含业务逻辑，只做协议适配。所有业务逻辑通过调用应用层服务完成。
//!
//! ## 目录结构
//!
//! - `http/` - HTTP 适配器（Axum handlers、路由、中间件）
//! - `cli/` - CLI 适配器（命令行解析、命令实现）
//!
//! ## 设计原则
//!
//! - **薄适配器**：入站适配层应该很薄，只做转换，不做业务判断
//! - **无状态**：入站适配层组件不应持有业务状态
//! - **依赖倒置**：入站适配层依赖应用层接口，不依赖领域层实现

